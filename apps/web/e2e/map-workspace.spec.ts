import { expect, test } from '@playwright/test';
import { afterMapPaint } from './_mapGeometry';

for (const width of [1774, 690, 390]) test(`context is a distinct in-page map view with shared camera and clearing at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 1050 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('/design/graph');
  const graph = page.locator('svg[aria-label^="Map of your concerns"]');
  await expect(graph).toBeVisible();
  await expect(graph.locator('[data-pebble-object]').first()).toHaveAttribute('data-pebble-pose', 'still');
  await page.evaluate(afterMapPaint);
  const beforeGraph = await graph.boundingBox();
  const url = page.url();
  const contextButton = page.getByRole('tab', { name: 'Context map', exact: true });
  await expect(contextButton.locator('..').getByRole('tab')).toHaveCount(4);
  await expect(contextButton).toHaveAttribute('data-variant', 'distinct');
  await contextButton.click();
  expect(page.url()).toBe(url);
  const context = page.locator('svg[aria-label="Your records context map"]');
  await expect(context).toBeVisible(); await page.evaluate(afterMapPaint);
  await expect(graph).not.toBeVisible();
  await expect(contextButton).toHaveAttribute('aria-selected', 'true');
  const bounds = (await context.boundingBox())!;
  expect(Math.abs(bounds.width / bounds.height - beforeGraph!.width / beforeGraph!.height)).toBeLessThan(0.02);
  const record = context.getByRole('button', { name: 'Monday note', exact: true });
  await record.press('Enter');
  await expect(record).toHaveAttribute('aria-pressed', 'true');
  await page.mouse.click(bounds.x + bounds.width / 2, bounds.y + bounds.height - 12);
  await expect(record).toHaveAttribute('aria-pressed', 'false');
  const camera = context.locator('[data-map-camera]');
  const initial = await camera.getAttribute('transform');
  await page.getByRole('button', { name: 'Zoom in', exact: true }).click();
  await expect(camera).not.toHaveAttribute('transform', initial!);
  const zoomed = await camera.getAttribute('transform');
  await record.press('Enter');
  await page.getByRole('tab', { name: 'Cluster detail', exact: true }).click();
  await expect(graph).toBeVisible();
  await contextButton.click();
  await expect(record).toHaveAttribute('aria-pressed', 'true');
  await expect(camera).toHaveAttribute('transform', zoomed!);
  await page.getByRole('button', { name: 'Recenter map', exact: true }).click();
  await expect(camera).toHaveAttribute('transform', initial!);
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width);
});
